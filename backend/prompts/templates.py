# 공통 출력 제약 지침
COMMON_INSTRUCTIONS = (
    "\n\n[출력 규칙]\n"
    "1. 어떠한 인사말, 설명, 부연설명(예: '변환된 문장입니다', '다음과 같이 작성했습니다' 등)도 절대 덧붙이지 마세요.\n"
    "2. 따옴표(\"\" 또는 '')나 마크다운 코드블록 없이 오직 변환된 비즈니스 메시지 본문만 즉시 출력하세요.\n"
    "3. 원문의 핵심 의도와 사실 관계를 왜곡하거나 누락하지 마세요."
)


def get_system_prompt(target_audience: str) -> str:
    """수신 대상 코드에 따른 완성형 시스템 프롬프트 반환"""
    base_prompt = SYSTEM_PROMPTS.get(
        target_audience,
        SYSTEM_PROMPTS["colleague"]
    )
    return base_prompt + COMMON_INSTRUCTIONS
